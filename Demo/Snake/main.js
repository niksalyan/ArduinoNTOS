// ========================================
// NTOS SNAKE
//
// Keypad:
//
//   1 2 3 A
//   4 5 6 B
//   7 8 9 C
//   * 0 # D
//
// 2 = UP
// 4 = LEFT
// 6 = RIGHT
// 8 = DOWN
// * = RESTART
//
// The snake moves automatically.
// Keys only change direction.
//
// ========================================


// ========================================
// GAME STATE
// ========================================

function init() {

    // ====================================
    // SNAKE
    // ====================================

    var x = [240,220,200,180,-100,-100,-100,-100,-100,-100,-100,-100];
    var y = [160,160,160,160,-100,-100,-100,-100,-100,-100,-100,-100];

    var length = 4;


    // ====================================
    // DIRECTION
    //
    // 1 = UP
    // 2 = DOWN
    // 3 = LEFT
    // 4 = RIGHT
    // ====================================

    var direction = 4;


    // ====================================
    // FOOD
    // ====================================

    var foodX = 320;
    var foodY = 160;


    // ====================================
    // SCORE
    // ====================================

    var score = 0;


    // ====================================
    // GAME STATE
    // ====================================

    var gameOver = 0;


    // ====================================
    // LOOP VARIABLE
    // ====================================

    var i = 0;
}


// ========================================
// UPDATE GAME
// ========================================

function update() {

    // ====================================
    // CLEAR PLAY AREA
    // ====================================

    fillBox(21, 31, 438, 268, BLACK);
	// ====================================
    // SCORE
    // ====================================

    cursor(30, 275, 2);
    print("SCORE: ", WHITE);

    print(score, YELLOW);

    // drawBox(20, 30, 440, 270, WHITE);


    // ====================================
    // FOOD
    // ====================================

    fillBox(foodX, foodY, 20, 20, RED);


    // ====================================
    // SNAKE
    // ====================================

    for (i = 0; i < length; i = i + 1) {

        fillBox(
            x[i],
            y[i],
            20,
            20,
            GREEN
        );
    }


    


    // ====================================
    // GAME OVER
    // ====================================

    if (gameOver == 1) {

        fillBox(100, 125, 280, 70, DARKRED);

        drawBox(100, 125, 280, 70, WHITE);

        cursor(165, 140, 3);
        print("GAME OVER", WHITE);

        cursor(125, 170, 2);
        print("PRESS * TO RESTART", WHITE);
    }
}



// ========================================
// DRAW GAME
// ========================================

function draw() {


	
    cls();

    fillBox(20, 30, 440, 270, BLACK);

    drawBox(20, 30, 440, 270, WHITE);

    update();
}


// ========================================
// INITIAL DRAW
// ========================================

draw();


// ========================================
// MAIN GAME LOOP
// ========================================

function loop() {

    // ====================================
    // READ KEYPAD
    //
    // This should be non-blocking.
    // If there is no key, the game
    // continues moving.
    // ====================================

    var key = getKey();


    // ====================================
    // RESTART
    // ====================================

    if (key == '*') {

        x[0] = 240;
        y[0] = 160;

        x[1] = 220;
        y[1] = 160;

        x[2] = 200;
        y[2] = 160;

        x[3] = 180;
        y[3] = 160;

        length = 4;

        direction = 4;

        foodX = 320;
        foodY = 160;

        score = 0;

        gameOver = 0;

        update();
    }


    // ====================================
    // PLAYING
    // ====================================

    if (gameOver == 0) {


        // =================================
        // CHANGE DIRECTION
        // =================================

        if (key == '2') {

            if (direction != 2) {
                direction = 1;
            }
        }


        if (key == '8') {

            if (direction != 1) {
                direction = 2;
            }
        }


        if (key == '4') {

            if (direction != 4) {
                direction = 3;
            }
        }


        if (key == '6') {

            if (direction != 3) {
                direction = 4;
            }
        }


        // =================================
        // MOVE BODY
        // =================================

        for (i = length - 1; i > 0; i = i - 1) {

            x[i] = x[i - 1];
            y[i] = y[i - 1];
        }


        // =================================
        // MOVE HEAD
        // =================================

        if (direction == 1) {
            y[0] = y[0] - 20;
        }

        if (direction == 2) {
            y[0] = y[0] + 20;
        }

        if (direction == 3) {
            x[0] = x[0] - 20;
        }

        if (direction == 4) {
            x[0] = x[0] + 20;
        }


        // =================================
        // WALL COLLISION
        // =================================

        if (x[0] < 40) {
            gameOver = 1;
        }

        if (x[0] > 420) {
            gameOver = 1;
        }

        if (y[0] < 50) {
            gameOver = 1;
        }

        if (y[0] > 270) {
            gameOver = 1;
        }


        // =================================
        // SELF COLLISION
        // =================================

        for (i = 1; i < length; i = i + 1) {

            if (x[0] == x[i] && y[0] == y[i]) {

                gameOver = 1;
            }
        }


        // =================================
        // FOOD
        // =================================

        if (x[0] == foodX && y[0] == foodY) {

            score = score + 1;


            // =================================
            // GROW
            // =================================

            if (length < 12) {

                length = length + 1;
            }


            // =================================
            // NEXT FOOD
            // =================================

            if (score == 1) {
                foodX = 100;
                foodY = 80;
            }

            if (score == 2) {
                foodX = 360;
                foodY = 80;
            }

            if (score == 3) {
                foodX = 100;
                foodY = 240;
            }

            if (score == 4) {
                foodX = 360;
                foodY = 240;
            }

            if (score == 5) {
                foodX = 200;
                foodY = 80;
            }

            if (score == 6) {
                foodX = 300;
                foodY = 80;
            }

            if (score == 7) {
                foodX = 200;
                foodY = 240;
            }

            if (score == 8) {
                foodX = 300;
                foodY = 240;
            }

            if (score == 9) {
                foodX = 60;
                foodY = 140;
            }

            if (score == 10) {
                foodX = 400;
                foodY = 140;
            }
        }


        // =================================
        // UPDATE SCREEN
        // =================================

        update();
    }


    // ====================================
    // GAME SPEED
    // ====================================

    delay(400);
}